export const getDeviceDefaultLanguage = (): SupportedLanguage => {
  if (typeof navigator !== 'undefined') {
    const navLangs = navigator.languages ? [...navigator.languages] : [navigator.language || ''];
    for (const lang of navLangs) {
      if (!lang) continue;
      const lower = lang.toLowerCase();
      if (lower.startsWith('hi')) return 'hi';
      if (lower.startsWith('mr')) return 'mr';
      if (lower.startsWith('te')) return 'te';
      if (lower.startsWith('ta')) return 'ta';
      if (lower.startsWith('bn')) return 'bn';
      if (lower.startsWith('en')) return 'en';
    }
  }
  return 'hi';
};
